-- TalkNow membership tables (prefix tn_) for shared DB sq_wele
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS tn_users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  phone VARCHAR(32) NOT NULL UNIQUE,
  display_name VARCHAR(128) NOT NULL DEFAULT '',
  frozen TINYINT NOT NULL DEFAULT 0,
  created_at VARCHAR(40) NOT NULL,
  updated_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_sessions (
  token CHAR(64) PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  created_at VARCHAR(40) NOT NULL,
  expires_at VARCHAR(40) NOT NULL,
  INDEX (user_id),
  FOREIGN KEY (user_id) REFERENCES tn_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_login_codes (
  phone VARCHAR(32) PRIMARY KEY,
  code VARCHAR(16) NOT NULL,
  expires_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_plans (
  id VARCHAR(32) PRIMARY KEY,
  name VARCHAR(64) NOT NULL,
  monthly_credits INT NOT NULL,
  gift_credits INT NOT NULL DEFAULT 0,
  price_month_cents INT NOT NULL,
  price_year_cents INT NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_subscriptions (
  user_id INT UNSIGNED PRIMARY KEY,
  plan_id VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'active',
  period_start VARCHAR(40) NOT NULL,
  period_end VARCHAR(40) NOT NULL,
  pending_plan_id VARCHAR(32) NOT NULL DEFAULT '',
  updated_at VARCHAR(40) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES tn_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_credit_accounts (
  user_id INT UNSIGNED PRIMARY KEY,
  balance INT NOT NULL DEFAULT 0,
  updated_at VARCHAR(40) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES tn_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_credit_ledger (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  delta INT NOT NULL,
  balance_after INT NOT NULL,
  reason VARCHAR(64) NOT NULL,
  grant_type VARCHAR(64) NOT NULL DEFAULT '',
  request_id VARCHAR(64) NOT NULL DEFAULT '',
  note VARCHAR(512) NOT NULL DEFAULT '',
  created_at VARCHAR(40) NOT NULL,
  INDEX (user_id),
  FOREIGN KEY (user_id) REFERENCES tn_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_orders (
  id VARCHAR(64) PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  source VARCHAR(32) NOT NULL,
  channel VARCHAR(32) NOT NULL DEFAULT '',
  external_trade_no VARCHAR(128) NOT NULL DEFAULT '',
  plan_id VARCHAR(32) NOT NULL DEFAULT '',
  credits INT NOT NULL DEFAULT 0,
  amount_cents INT NOT NULL DEFAULT 0,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  payment_note VARCHAR(512) NOT NULL DEFAULT '',
  created_at VARCHAR(40) NOT NULL,
  paid_at VARCHAR(40) NOT NULL DEFAULT '',
  INDEX (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_model_routes (
  slot VARCHAR(32) PRIMARY KEY,
  base_url VARCHAR(512) NOT NULL,
  api_key VARCHAR(512) NOT NULL,
  model_id VARCHAR(256) NOT NULL,
  updated_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_credit_prices (
  `key` VARCHAR(64) PRIMARY KEY,
  value INT NOT NULL,
  updated_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_redeem_codes (
  code VARCHAR(64) PRIMARY KEY,
  credits INT NOT NULL,
  max_uses INT NOT NULL DEFAULT 1,
  used_count INT NOT NULL DEFAULT 0,
  expires_at VARCHAR(40) NOT NULL DEFAULT '',
  note VARCHAR(256) NOT NULL DEFAULT '',
  created_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_app_settings (
  `key` VARCHAR(64) PRIMARY KEY,
  value TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_admin_sessions (
  token CHAR(64) PRIMARY KEY,
  created_at VARCHAR(40) NOT NULL,
  expires_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_kb_articles (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(128) NOT NULL UNIQUE,
  title VARCHAR(256) NOT NULL,
  category VARCHAR(64) NOT NULL DEFAULT 'general',
  body MEDIUMTEXT NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  updated_at VARCHAR(40) NOT NULL,
  created_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS tn_roadmap_items (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  phase VARCHAR(64) NOT NULL DEFAULT '',
  title VARCHAR(256) NOT NULL,
  detail TEXT NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  sort_order INT NOT NULL DEFAULT 0,
  updated_at VARCHAR(40) NOT NULL,
  created_at VARCHAR(40) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
