#!/usr/bin/env node
/**
 * Sync src/shared/plan-catalog.json → website/js/plan-catalog.js
 */
import { readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'src/shared/plan-catalog.json')
const dest = join(root, 'website/js/plan-catalog.js')
const payload = JSON.parse(readFileSync(src, 'utf8'))

const out = `/* AUTO-GENERATED by scripts/sync-plan-catalog.mjs — do not edit by hand.
 * Source: src/shared/plan-catalog.json
 * Run: npm run sync:plans
 */
;(function (global) {
  var DATA = ${JSON.stringify(payload, null, 2)};

  function rank(id) {
    var i = DATA.order.indexOf(id);
    return i >= 0 ? i : 50;
  }

  function sortPlans(list) {
    return (list || []).slice().sort(function (a, b) {
      var ra = rank(a.id);
      var rb = rank(b.id);
      if (ra !== rb) return ra - rb;
      return (a.monthlyCredits || 0) - (b.monthlyCredits || 0);
    });
  }

  function featured(id) {
    var e = DATA.catalog[id];
    return !!(e && e.featured);
  }

  function featureKinds(id) {
    var e = DATA.catalog[id] || DATA.catalog.trial;
    return (e && e.featureKinds) || ['credits', 'officialSlots', 'byok'];
  }

  function fallbackPlans(lang) {
    var en = lang === 'en';
    return DATA.fallback.map(function (p) {
      return {
        id: p.id,
        name: en ? p.nameEn : p.nameZh,
        baseCredits: p.baseCredits,
        giftCredits: p.giftCredits,
        monthlyCredits: p.baseCredits + p.giftCredits,
        priceMonthCents: p.priceMonthCents,
        priceYearCents: p.priceYearCents
      };
    });
  }

  global.TalkNowPlans = {
    DATA: DATA,
    PLANS_API: DATA.plansApi,
    rank: rank,
    sortPlans: sortPlans,
    featured: featured,
    featureKinds: featureKinds,
    fallbackPlans: fallbackPlans,
    topupFallback: function () {
      return DATA.topupFallback;
    }
  };
})(typeof window !== 'undefined' ? window : globalThis);
`

writeFileSync(dest, out, 'utf8')
console.log('Wrote', dest)
